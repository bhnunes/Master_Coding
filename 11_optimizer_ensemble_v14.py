def compute_ensemble_iterative(memmaps, model_indices, weights, global_indices, shape_h, shape_w):
    # Allocate accumulator (Float32) - ONE copy in RAM
    n_frames = len(global_indices)
    accumulator = np.zeros((n_frames, shape_h, shape_w), dtype=np.float32)

    # Pre-calculate scale factor
    scale = 1.0 / 65535.0

    for m_idx, w in zip(model_indices, weights):
        if w <= 1e-5: continue # Skip zero-weight models

        # 1. Load ONE model's data from disk
        # This is the only moment high RAM is used for raw data
        chunk = memmaps[m_idx][global_indices]

        # 2. Add to accumulator and scale on the fly
        # We use in-place addition to save memory
        accumulator += chunk.astype(np.float32) * (w * scale)

        # 3. CRITICAL: Delete the chunk immediately
        del chunk

    return accumulator

