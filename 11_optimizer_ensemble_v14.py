def generate_roi_batch(probs_tensor, context_scale, threshold):
    """
    Generates binary ROI masks using low-pass approach:
    Downsample -> Threshold -> Upsample (Nearest)
    Input: probs_tensor [B, H, W] (float)
    Output: roi_mask [B, H, W] (bool/uint8)
    """
    B, H, W = probs_tensor.shape
    # 1. Downsample (Low-pass)
    # Unsqueeze for interpolate [B, 1, H, W]
    small = F.interpolate(probs_tensor.unsqueeze(1), scale_factor=1.0/context_scale, mode='bilinear', align_corners=False)

    # 2. Threshold (Operating Point)
    mask_small = (small > threshold).float()

    # 3. Upsample (Nearest to keep binary edges)
    mask_large = F.interpolate(mask_small, size=(H, W), mode='nearest').squeeze(1)

    return mask_large # [B, H, W] 0.0 or 1.0

def compute_patient_auprc_in_roi(y_true, y_pred, roi_mask):
    """
    Compute AUPRC only for pixels INSIDE the ROI.
    y_true, y_pred, roi_mask: flattened 1D arrays for a single patient.
    """
    # Filter by ROI
    valid_indices = (roi_mask > 0)

    # Guard: Empty ROI
    if not np.any(valid_indices):
        return 0.0

    y_true_roi = y_true[valid_indices]
    y_pred_roi = y_pred[valid_indices]

    # Guard: No positive pixels in ROI (Target is all 0) -> AUPRC undefined/0
    if np.sum(y_true_roi) == 0:
        return 0.0

    try:
        return average_precision_score(y_true_roi, y_pred_roi)
    except:
        return 0.0

@torch.inference_mode()
def predict_with_tta_batched(model, images, amp):
    """
    TTA = {orig, hflip, vflip} executed SEQUENTIALLY to save memory.

    Previous version: [3*B, C, H, W] -> Peak Memory: High
    This version:     [B, C, H, W] x 3 -> Peak Memory: Low (1/3rd)
    """
    # 1. Forward Pass (Original)
    with torch.amp.autocast('cuda', enabled=True, dtype=amp):
        out = model(images)
        if isinstance(out, (tuple, list)): out = out[0]

        # Convert to probabilities
        if out.shape[1] == 1:
            probs = torch.sigmoid(out).squeeze(1)
        else:
            probs = torch.softmax(out, dim=1)[:, 1, :, :]

    # 2. Horizontal Flip (Input Flip -> Forward -> Output Flip)
    images_h = torch.flip(images, dims=[3])
    with torch.amp.autocast('cuda', enabled=True, dtype=amp):
        out_h = model(images_h)
        if isinstance(out_h, (tuple, list)): out_h = out_h[0]

        if out_h.shape[1] == 1:
            p_h = torch.sigmoid(out_h).squeeze(1)
        else:
            p_h = torch.softmax(out_h, dim=1)[:, 1, :, :]

    # Accumulate in-place (Un-flip Width axis 2)
    probs.add_(torch.flip(p_h, dims=[2]))
    # Free memory immediately
    del images_h, out_h, p_h

    # 3. Vertical Flip
    images_v = torch.flip(images, dims=[2])
    with torch.amp.autocast('cuda', enabled=True, dtype=amp):
        out_v = model(images_v)
        if isinstance(out_v, (tuple, list)): out_v = out_v[0]

        if out_v.shape[1] == 1:
            p_v = torch.sigmoid(out_v).squeeze(1)
        else:
            p_v = torch.softmax(out_v, dim=1)[:, 1, :, :]

    # Accumulate in-place (Un-flip Height axis 1)
    probs.add_(torch.flip(p_v, dims=[1]))
    # Free memory
    del images_v, out_v, p_v

    # Average
    probs.div_(3.0)
    return probs

def cache_predictions_sequential(models_list, dataloader, device, cache_dir):
    print(f"\n--- Caching Predictions (Sequential, Optimized Uint16) to {cache_dir} ---")
    if os.path.exists(cache_dir): shutil.rmtree(cache_dir)
    os.makedirs(cache_dir, exist_ok=True)

    # 1. Initialize sizes
    print("Initializing cache size...")
    N_total = 0
    H, W = 0, 0
    for b in dataloader:
        if b is None: continue
        img = b[0]
        if img is not None:
            N_total += img.shape[0]
            if H == 0: H, W = img.shape[2], img.shape[3]
            # Break after first valid batch to save time
            break

    # Recalculate N_total correctly
    N_total = len(dataloader.dataset)
    print(f"Total samples: {N_total}, Shape: {H}x{W}")

    # Memmap for GTs (uint8)
    trues_path = os.path.join(cache_dir, "trues.dat")
    trues_mm = np.memmap(trues_path, dtype='uint8', mode='w+', shape=(N_total, H, W))

    pred_paths = []
    pids = []

    # 2. Sequential Model Inference
    first_pass = True

    for m_idx, model in enumerate(models_list):
        arch = getattr(model, 'arch_name', 'UNK')
        print(f"Processing Model {m_idx+1}/{len(models_list)}: {arch}")

        model.to(device).eval()
        amp = setup_inference_precision(arch)

        # OPTIMIZATION: Use uint16 to save 50% disk I/O and space
        p_path = os.path.join(cache_dir, f"pred_{m_idx}.dat")
        pred_mm = np.memmap(p_path, dtype='uint16', mode='w+', shape=(N_total, H, W))

        w_pos = 0
        for batch in tqdm(dataloader, desc=f"Infer {arch}"):
            if batch is None: continue

            # Handle tuple size variation
            if len(batch) == 3: imgs, masks, batch_pids = batch
            elif len(batch) == 4: imgs, _, masks, batch_pids = batch
            else: imgs, _, masks, batch_pids, _ = batch

            bs = imgs.shape[0]

            # Save GTs/PIDs only on first pass
            if first_pass:
                trues_mm[w_pos:w_pos+bs] = masks[:, 1, :, :].cpu().numpy().astype('uint8')
                pids.extend(batch_pids)

            # Inference
            imgs = imgs.to(device)
            imgs = gpu_normalizer(imgs) # <--- INSERTED HERE
            p = predict_with_tta_batched(model, imgs, amp)
            p = p.detach().float().cpu().numpy()


            # --- SAFETY GUARD FOR DPT/MANET ---
            # 1. Handle potential NaNs from the model itself (replace with 0.0)
            # 2. Handle rare float errors slightly < 0 or > 1
            # 3. Ensure strictly [0, 1] before scaling
            p = np.nan_to_num(p, nan=0.0, posinf=1.0, neginf=0.0)
            p = np.clip(p, 0.0, 1.0)

            # OPTIMIZATION: Quantize to uint16 (0-65535)
            # This preserves 1.5e-5 precision, sufficient for scientific segmentation
            p_quantized = (p * 65535).astype(np.uint16)

            pred_mm[w_pos:w_pos+bs] = p_quantized
            w_pos += bs


        pred_mm.flush()
        model.cpu()
        clear_gpu()

        pred_paths.append(p_path)
        if first_pass:
            trues_mm.flush()
            first_pass = False

    if w_pos != N_total:
        raise RuntimeError(f"Cached {w_pos} samples but expected {N_total}. Dataset produced None/filtered items.")

    with open(os.path.join(cache_dir, "pids.json"), 'w') as f: json.dump(pids, f)

    return pred_paths, trues_path, os.path.join(cache_dir, "pids.json"), N_total, H, W, trues_mm

