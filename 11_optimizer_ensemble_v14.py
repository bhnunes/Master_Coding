def setup_inference_precision(architecture: str):
    """
    Sets global precision flags and returns the autocast dtype for inference.
    (Simplified version of training setup: No GradScaler needed).
    """

    architecture = str(architecture).upper().strip()

    # --- TIER 1: STRICT FP32 (DPT) ---
    if architecture == "DPT":
        try:
            torch.set_float32_matmul_precision('highest') # IEEE FP32
        except Exception:
            pass
        return torch.float32

    # --- TIER 2: MEDIUM PRECISION (Transformers) ---
    if architecture in ["SWIN", "SEGFORMER"]:
        try:
            torch.set_float32_matmul_precision('medium') # BF16/TF32 MatMul
        except Exception:
            pass
    else:
        # --- TIER 3: HIGH PRECISION (CNNs/Standard) ---
        try:
            torch.set_float32_matmul_precision('high') # TF32 MatMul
        except Exception:
            pass

    # --- AMP Dtype Selection ---
    # Use BF16 if available (more stable than FP16), otherwise FP16
    if torch.cuda.is_available() and torch.cuda.is_bf16_supported():
        return torch.bfloat16
    else:
        return torch.float16

