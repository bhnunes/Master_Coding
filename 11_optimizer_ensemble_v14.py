def postprocess_binary_mask_np(pred_mask_uint8, min_area, open_ksize):
    """
    Applies morphological opening and area filtering to a binary mask (H, W).
    Input: pred_mask_uint8 (0 or 1), numpy array.
    """
    # 1. Morphological Opening
    if open_ksize > 0:
        kernel = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (open_ksize, open_ksize))
        pred_mask_uint8 = cv2.morphologyEx(pred_mask_uint8, cv2.MORPH_OPEN, kernel)

    # 2. Area Filtering
    if min_area > 0:
        # cv2.connectedComponentsWithStats takes uint8 image
        num_labels, labels, stats, centroids = cv2.connectedComponentsWithStats(pred_mask_uint8, connectivity=8)

        # stats: [x, y, width, height, area]
        # Label 0 is background
        for i in range(1, num_labels):
            area = stats[i, cv2.CC_STAT_AREA]
            if area < min_area:
                pred_mask_uint8[labels == i] = 0

    return pred_mask_uint8

def compute_global_metrics_from_counts(tp: int, fp: int, fn: int, tn: int, smooth: float = 1e-6):
    """
    Compute micro Dice, IoU and MCC from global TP/FP/FN/TN counts.

    Returns:
        dice_micro (float), iou (float), mcc (float)
    """
    # Micro Dice over all pixels
    denom_dice = 2 * tp + fp + fn
    if denom_dice > 0:
        dice_micro = float((2.0 * tp + smooth) / (denom_dice + smooth))
    else:
        dice_micro = 0.0

    # IoU (Jaccard)
    denom_iou = tp + fp + fn
    if denom_iou > 0:
        iou = float((tp + smooth) / (denom_iou + smooth))
    else:
        iou = 0.0

    # Matthews Correlation Coefficient
    tp_fp = tp + fp
    tp_fn = tp + fn
    tn_fp = tn + fp
    tn_fn = tn + fn

    denom_mcc = (tp_fp * tp_fn * tn_fp * tn_fn) ** 0.5
    if denom_mcc > 0:
        mcc = float((tp * tn - fp * fn) / (denom_mcc + 1e-12))
    else:
        mcc = 0.0

    return dice_micro, iou, mcc

