class ProstateCancerDatasetHDF5(Dataset):
    def __init__(
        self,
        hdf5_path,
        mode="validation",
        return_context=False, # Required for Stage 2 Gating
        context_scale=1       # Required for LowPass simulation
    ):
        self.hdf5_path = hdf5_path
        self.mode = mode
        self.return_context = return_context
        self.context_scale = int(context_scale)

        self.transform = get_transforms(mode=mode, img_size=224)

        # --- METADATA LOADING ---
        with h5py.File(self.hdf5_path, 'r') as f:
            self.full_pids = f["patient_ids"][:]
            self.total_len = len(self.full_pids)

        self.h5_file = None
        self.images_dset = None
        self.masks_dset = None
        self._opened_pid = None
        self._atexit_registered = False

    def _open_file(self):
        """Open the HDF5 file lazily (per-process safe).

        DataLoader with num_workers>0 forks/spawns worker processes. Each worker must
        hold its own independent HDF5 file handle. We therefore:
          - open on first access inside the current process
          - if the dataset object crosses a process boundary, close/reopen
          - register an atexit hook (once per process) to close cleanly
        """
        pid = os.getpid()

        # If we were opened in a different process (e.g., fork), close and reopen here.
        if self.h5_file is not None and self._opened_pid is not None and self._opened_pid != pid:
            self.close()

        if self.h5_file is None:
            # 50MB raw data chunk cache is sufficient for sequential-ish reading
            self.h5_file = h5py.File(
                self.hdf5_path,
                "r",
                libver="latest",
                rdcc_nbytes=50 * 1024 * 1024,
            )
            self.images_dset = self.h5_file["images"]
            self.masks_dset = self.h5_file["masks"]
            self._opened_pid = pid

            if not self._atexit_registered:
                # Ensure clean close when worker exits (best-effort).
                atexit.register(self.close)
                self._atexit_registered = True

    def __len__(self):
        return self.total_len

    def __getitem__(self, idx):
        if self.h5_file is None: self._open_file()

        # 1. Load Raw Data
        image = self.images_dset[idx] # uint8 [224,224,3]
        mask  = self.masks_dset[idx]  # uint8 [224,224]
        patient_id = str(self.full_pids[idx]) # Ensure string ID

        # 2. Prepare Mask (2-channel float for consistency)
        two_channel_mask = np.zeros((mask.shape[0], mask.shape[1], 2), dtype=np.float32)
        two_channel_mask[mask == 0, 0] = 1.0
        two_channel_mask[mask != 0, 1] = 1.0

        try:
            # 3. Augmentations
            augmented = self.transform(image=image, mask=two_channel_mask)
            final_image = augmented['image'] # Tensor [3, 224, 224]
            final_mask = augmented['mask']   # Tensor [224, 224, 2] usually

            # Fix Permutation: Albumentations returns (H,W,C), PyTorch needs (C,H,W)
            if final_mask.shape[0] != 2:
                final_mask = final_mask.permute(2, 0, 1)
            if final_mask.ndim != 3 or final_mask.shape[0] != 2:
              raise ValueError(
                  f"[HDF5Dataset] Unexpected mask shape after transforms: {tuple(final_mask.shape)} "
                  f"(expected (2,H,W)). Check Albumentations pipeline / ToTensorV2 behavior."
              )

            # 4. Context Gating (LowPass Simulation)
            if self.return_context:
                _, h, w = final_image.shape
                scale = max(1, self.context_scale)
                small_h, small_w = h // scale, w // scale

                # Downsample -> Upsample (Simulate Zoom Out)
                img_unsqueezed = final_image.unsqueeze(0)
                ctx_small = F.interpolate(img_unsqueezed, size=(small_h, small_w), mode='bilinear', align_corners=False)
                ctx_full = F.interpolate(ctx_small, size=(h, w), mode='bilinear', align_corners=False)

                final_context = ctx_full.squeeze(0)

                # Return 4 items: Image, Context, Mask, PID
                return final_image, final_context, final_mask, patient_id

            return final_image, final_mask, patient_id

        except Exception as e:
            print(f"Error on index {idx}: {e}")
            if self.return_context: return None, None, None, None
            return None, None, None

    # Required for stratifying holdout sets
    def get_patient_ids(self):
        return [str(p) for p in self.full_pids]

    def close(self):
        """Close any open HDF5 handle (safe to call multiple times)."""
        try:
            if getattr(self, "h5_file", None) is not None:
                try:
                    self.h5_file.close()
                except Exception:
                    pass
        finally:
            self.h5_file = None
            self.images_dset = None
            self.masks_dset = None
            self._opened_pid = None

    def __del__(self):
        # Best-effort cleanup (do not raise in GC).
        try:
            self.close()
        except Exception:
            pass

    def __getstate__(self):
        """Make dataset picklable by dropping live HDF5 handles."""
        state = self.__dict__.copy()
        # Never pickle open file handles / datasets.
        state["h5_file"] = None
        state["images_dset"] = None
        state["masks_dset"] = None
        state["_opened_pid"] = None
        state["_atexit_registered"] = False
        return state

    def __setstate__(self, state):
        self.__dict__.update(state)
        # Ensure handles are closed until first access in this process.
        self.h5_file = None
        self.images_dset = None
        self.masks_dset = None
        self._opened_pid = None
        self._atexit_registered = False

class GPUNormalizer(torch.nn.Module):
    def __init__(self, mean, std, device):
        super().__init__()
        # Register as buffers so they move to device automatically with the model
        self.register_buffer("mean", torch.tensor(mean, device=device).view(1, 3, 1, 1))
        self.register_buffer("std", torch.tensor(std, device=device).view(1, 3, 1, 1))

    @torch.no_grad()
    def forward(self, x: torch.Tensor) -> torch.Tensor:
        """
        Input x: [B, 3, H, W]
        """
        # CASE 1: Input is Byte/Uint8 (0-255).
        # This is what comes from ToTensorV2() with uint8 source.
        if x.dtype == torch.uint8:
            x = x.float() / 255.0

        # CASE 2: Input is Float, but large magnitude (0-255).
        # This happens if an augmentation inadvertently cast to float but didn't normalize.
        # We use a safe threshold. ImageNet data is never > 10.0 after normalization.
        elif x.max() > 2.0:
             x = x / 255.0

        # CASE 3: Input is already float [0, 1].
        # We do nothing.

        # Finally, normalize with Mean/Std
        return (x - self.mean) / self.std

# --- SHARED: Updated Collate Function ---
def collate_fn(batch):
    # Filter None
    batch = list(filter(lambda x: x is not None and x[0] is not None, batch))
    if not batch: return None

    # Detect tuple size from first valid item
    sample_len = len(batch[0])

    if sample_len == 3:
        # Standard: (img, mask, pid)
        images = torch.utils.data.dataloader.default_collate([b[0] for b in batch])
        masks = torch.utils.data.dataloader.default_collate([b[1] for b in batch])
        pids = [b[2] for b in batch]
        return images, masks, pids

    elif sample_len == 4:
        # Context: (img, img_ctx, mask, pid)
        images = torch.utils.data.dataloader.default_collate([b[0] for b in batch])
        images_ctx = torch.utils.data.dataloader.default_collate([b[1] for b in batch])
        masks = torch.utils.data.dataloader.default_collate([b[2] for b in batch])
        pids = [b[3] for b in batch]
        return images, images_ctx, masks, pids

    elif sample_len == 5:
        images = torch.utils.data.dataloader.default_collate([b[0] for b in batch])
        images_ctx = torch.utils.data.dataloader.default_collate([b[1] for b in batch])
        masks = torch.utils.data.dataloader.default_collate([b[2] for b in batch])
        pids = [b[3] for b in batch]
        pos = torch.as_tensor([b[4] for b in batch], dtype=torch.long)
        return images, images_ctx, masks, pids, pos

    else:
        raise ValueError(f"Unexpected batch item length: {sample_len}")

def load_checkpoint_strict_without_aux(model, chkpt_path, device):
    # 1) Load checkpoint safely on CPU
    chkpt = torch.load(chkpt_path, map_location="cpu")

    # 2) Extract model state dict
    state_dict = chkpt.get("model_state_dict", chkpt)

    # 3) Drop auxiliary / classification head keys if present
    state_dict = {
        k: v for k, v in state_dict.items()
        if not k.startswith("classification_head.")
    }

    # 4) Load STRICTLY while model is still on CPU
    missing, unexpected = model.load_state_dict(state_dict, strict=True)

    if unexpected:
        print(f"[WARN] Unexpected keys: {unexpected[:5]}{'...' if len(unexpected) > 5 else ''}")
    if missing:
        print(f"[WARN] Missing keys: {missing[:5]}{'...' if len(missing) > 5 else ''}")

    # 5) Move model to device (single allocation)
    model.to(device)

    # 6) Re-compile ONLY if original model was compiled
    if chkpt.get("is_compiled", False):
        print("[INFO] Re-compiling model (checkpoint was compiled)")
        try:
            model = torch.compile(model)
        except Exception as e:
            print(f"[WARN] torch.compile failed: {e}")

    return model

def compute_metrics_histogram(weights, trues_mm, indices, H, W, chunk_size, tpr_target, sec_metric, pred_mms):
    """
    Computes global metrics for ALL thresholds simultaneously using histograms.
    Complexity: O(N) over pixels (single pass) + O(B) over bins, instead of O(N * T).
    Optimized aggregation via np.bincount (faster than np.add.at).
    """

    # 1) Setup Histograms
    # 4096 bins gives resolution of ~0.00024
    N_BINS = 4096
    hist_pos = np.zeros(N_BINS + 1, dtype=np.int64)
    hist_neg = np.zeros(N_BINS + 1, dtype=np.int64)

    weights = np.asarray(weights, dtype=np.float32)

    # Filter active weights to reduce compute
    active_m_indices = [i for i, w in enumerate(weights) if w > 1e-5]
    active_weights = weights[active_m_indices]

    # Precompute effective weights for uint16 decoding:
    # pred_uint16 in [0,65535] -> prob in [0,1] via * (1/65535)
    # fused into weight multiplication for speed
    active_w_eff = active_weights * (1.0 / 65535.0)

    # 2) Stream Data and Build Histograms
    # Ensure indices are numpy for slicing speed (optional but usually helpful)
    indices = np.asarray(indices)

    for i in range(0, len(indices), chunk_size):
        chunk_idx = indices[i:i + chunk_size]

        # Load GT (boolean mask)
        gt_chunk = (trues_mm[chunk_idx] > 0)

        # Weighted ensemble probability for this chunk
        ens_chunk = np.zeros(gt_chunk.shape, dtype=np.float32)

        # Accumulate only active models
        for local_i, global_m_i in enumerate(active_m_indices):
            raw_u16 = pred_mms[global_m_i][chunk_idx]  # uint16 memmap slice
            ens_chunk += raw_u16.astype(np.float32) * active_w_eff[local_i]

        # Clip to [0,1] (safety)
        np.clip(ens_chunk, 0.0, 1.0, out=ens_chunk)

        # Quantize to bins: p in [0,1] -> bin in [0, N_BINS]
        # Important: clip to N_BINS to avoid rare overflow due to float rounding at 1.0
        bin_indices = (ens_chunk * N_BINS).astype(np.int32)
        np.clip(bin_indices, 0, N_BINS, out=bin_indices)

        # Split into pos/neg bins and aggregate via bincount
        pos_bins = bin_indices[gt_chunk].ravel()
        if pos_bins.size:
            hist_pos += np.bincount(pos_bins, minlength=N_BINS + 1)

        neg_bins = bin_indices[~gt_chunk].ravel()
        if neg_bins.size:
            hist_neg += np.bincount(neg_bins, minlength=N_BINS + 1)

    # 3) Compute Metrics via Cumulative Sums (suffix sums over bins)
    # We want counts for p >= thr, which corresponds to bin >= b.
    # Reverse + cumsum + reverse gives suffix sums.
    tp_cum = np.cumsum(hist_pos[::-1])[::-1]
    fp_cum = np.cumsum(hist_neg[::-1])[::-1]

    total_pos = int(tp_cum[0])
    total_neg = int(fp_cum[0])

    # ---------------------------
    # HARD ASSERTS (fail fast)
    # ---------------------------
    if total_pos <= 0:
        raise RuntimeError(
            f"[compute_metrics_histogram] Degenerate pool: total_pos={total_pos}. "
            "No positive pixels in optimization pool => TPR/MCC selection is invalid."
        )
    if total_neg <= 0:
        raise RuntimeError(
            f"[compute_metrics_histogram] Degenerate pool: total_neg={total_neg}. "
            "No negative pixels in optimization pool => TNR/MCC selection is invalid."
        )

    fn_cum = total_pos - tp_cum
    tn_cum = total_neg - fp_cum

    # 4) Metric vectors
    EPS = 1e-7
    tpr_vec = tp_cum.astype(np.float64) / (total_pos + EPS)

    tnr_vec = tn_cum.astype(np.float64) / (total_neg + EPS)
    if not np.all(np.isfinite(tnr_vec)):
        bad = np.where(~np.isfinite(tnr_vec))[0][:10]
        raise RuntimeError(
            f"[compute_metrics_histogram] Non-finite values in tnr_vec at bins {bad.tolist()} "
            f"(total_pos={total_pos}, total_neg={total_neg})."
        )

    # MCC denominator in float64 to avoid int64 overflow
    a = (tp_cum + fp_cum).astype(np.float64)
    b = (tp_cum + fn_cum).astype(np.float64)
    c = (tn_cum + fp_cum).astype(np.float64)
    d = (tn_cum + fn_cum).astype(np.float64)

    denom2 = a * b * c * d
    # Guard against tiny negative due to floating-point roundoff (should be rare)
    denom2 = np.maximum(denom2, 0.0)
    denom = np.sqrt(denom2)

    num = (tp_cum.astype(np.float64) * tn_cum.astype(np.float64) -
          fp_cum.astype(np.float64) * fn_cum.astype(np.float64))
    mcc_vec = num / (denom + EPS)

    # Only required when sec_metric == "mcc", but checking here is cheap and safer
    if sec_metric == "mcc":
        if not np.all(np.isfinite(mcc_vec)):
            bad = np.where(~np.isfinite(mcc_vec))[0][:10]
            raise RuntimeError(
                f"[compute_metrics_histogram] Non-finite values in mcc_vec at bins {bad.tolist()} "
                f"(total_pos={total_pos}, total_neg={total_neg})."
            )

    # If you want float32 downstream (optional)
    tpr_vec = tpr_vec.astype(np.float32)
    tnr_vec = tnr_vec.astype(np.float32)
    mcc_vec = mcc_vec.astype(np.float32)

    # Threshold value per bin (consistent with binning rule: bin = floor(p*N_BINS))
    thresholds_vec = np.linspace(0.0, 1.0, N_BINS + 1, dtype=np.float32)

    # 5) Select best threshold subject to TPR constraint
    valid = np.where(tpr_vec >= tpr_target)[0]

    if valid.size:
        if sec_metric == "tnr":
            best_local_idx = valid[np.argmax(tnr_vec[valid])]
            best_score = float(tnr_vec[best_local_idx])
        else:
            best_local_idx = valid[np.argmax(mcc_vec[valid])]
            best_score = float(mcc_vec[best_local_idx])
    else:
        # Fallback: maximize TPR if target unreachable
        best_local_idx = int(np.argmax(tpr_vec))
        best_score = float(tnr_vec[best_local_idx] if sec_metric == "tnr" else mcc_vec[best_local_idx])

    return float(thresholds_vec[best_local_idx]), best_score

def check_patient_collapse_streamed(weights, pred_mms, trues_mm, pat_map, patient_list, thr, tpr_floor):
    tpr_sum = 0
    n_pats = 0
    weights = np.array(weights, dtype=np.float32)
    active_indices = [i for i, w in enumerate(weights) if w > 1e-4]

    for p in patient_list:
        idxs = pat_map[p]
        pat_gt = trues_mm[idxs]
        if np.sum(pat_gt) == 0: continue

        # Compute Ensemble for this patient
        pat_ens = np.zeros(pat_gt.shape, dtype=np.float32)
        for mi in active_indices:
            # Decode uint16 -> float
            w_eff = weights[mi] / 65535.0
            pat_ens += pred_mms[mi][idxs].astype(np.float32) * w_eff

        tp = np.sum((pat_ens >= thr) & (pat_gt == 1))
        fn = np.sum((pat_ens < thr)  & (pat_gt == 1))

        tpr = tp / (tp + fn + 1e-7)
        tpr_sum += tpr
        n_pats += 1

    if n_pats == 0: return 1.0
    return tpr_sum / n_pats

def pick_n(total, frac):
    if total <= 1:
        return 0  # can't hold out without killing opt pool
    # at least 1, but leave at least 1 for opt
    return min(max(1, int(round(total * frac))), total - 1)

