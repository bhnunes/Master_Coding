def objective_semantic_streaming(trial):
    # 1. Suggest Weights
    ws = [trial.suggest_float(f"w_sem_{i}", 0.0, 1.0) for i in range(len(sem_indices))]
    w_sum = sum(ws) + 1e-9
    ws = [w/w_sum for w in ws] # Normalize

    # 2. Suggest ROI Operating Point
    # FIX: Increased lower bound from 0.05 to 0.15.
    # 0.05 captures background noise, causing "Trivial Permissive" pruning.
    roi_thresh = trial.suggest_float("roi_thresh", 0.15, 0.60)

    # 3. Stream Processing (Patient-wise) to save RAM
    roi_area_fracs = []
    roi_pos_recalls = []
    n_empty_rois = 0

    # Pre-calculate effective weights for uint16->float conversion
    # w_eff[i] = weight[i] / 65535.0
    w_eff_list = [w / 65535.0 for w in ws]

    # Iterate over patients instead of loading full dataset
    for p in opt_pats:
        sl = opt_pat_map_local[p]

        pat_global_indices = opt_idx[sl]

        pat_u16_arrays = [pred_mms[i][pat_global_indices] for i in sem_indices]

        # Weighted sum (Numpy is efficient here for small chunks)
        # pat_ens shape: [Frames, H, W]
        pat_ens = np.zeros(pat_u16_arrays[0].shape, dtype=np.float32)
        for i, u16_arr in enumerate(pat_u16_arrays):
            if w_eff_list[i] > 1e-7:
                pat_ens += u16_arr.astype(np.float32) * w_eff_list[i]

        # B. Generate ROI (Using Torch on CPU for this small chunk)
        # This keeps peak memory low (Batch Size = Patient Size)
        t_probs = torch.from_numpy(pat_ens)
        t_roi = generate_roi_batch(t_probs, ROI_CONTEXT_SCALE, roi_thresh)
        p_roi = t_roi.numpy().astype(np.uint8) # [Frames, H, W]

        # C. Get Ground Truth
        p_gt = opt_gt_u8[sl]

        # D. Metrics
        area_frac = np.mean(p_roi)
        roi_area_fracs.append(area_frac)

        if np.sum(p_roi) == 0:
            n_empty_rois += 1

        is_pos_pat = (np.sum(p_gt) > 0)
        if is_pos_pat:
            # Intersection count
            # Use bitwise & for speed on uint8/bool
            intersection = np.sum((p_roi == 1) & (p_gt == 1))
            total_pos = np.sum(p_gt)
            recall = intersection / (total_pos + 1e-7)
            roi_pos_recalls.append(recall)

        # E. Explicit cleanup (Optional but safe)
        del pat_ens, t_probs, t_roi, p_roi, pat_u16_arrays

    # 4. Aggregates
    median_area = np.median(roi_area_fracs) if roi_area_fracs else 0.0
    empty_rate = n_empty_rois / len(opt_pats)
    mean_pos_recall = np.mean(roi_pos_recalls) if roi_pos_recalls else 0.0

    # 5. Guardrails
    # =========================================================================
    # UPDATED GUARDRAILS (Sensitive to Dense Data)
    # =========================================================================

    # Check 1: Empty ROI (Still bad, keep this)
    if empty_rate > ROI_EMPTY_MAX:
        raise optuna.exceptions.TrialPruned(f"Trivial Empty: {empty_rate:.2f}")

    # Check 2: Misses Positives (Still bad, keep this)
    if mean_pos_recall < ROI_MIN_POS_RECALL:
        raise optuna.exceptions.TrialPruned(f"Misses Positives: {mean_pos_recall:.2f}")

    # Check 3: Trivial Permissive (RELAXED)
    # If the Ground Truth itself is dense (e.g. >50% tumor), we must allow high area.
    # We estimate GT density from the loaded `p_gt` slices.

    # Calculate GT density for the opt set
    gt_densities = []
    for p in opt_pats:
        sl = opt_pat_map_local[p]
        gt_densities.append(np.mean(opt_gt_u8[sl]))
    mean_gt_density = np.mean(gt_densities) if gt_densities else 0.0

    # Dynamic Ceiling: Allow ROI to be slightly larger than GT density
    # If GT is 0.9 (90% tumor), allow ROI up to 0.99
    # If GT is 0.01 (1% tumor), allow ROI up to 0.60
    dynamic_max_median = max(ROI_MAX_MEDIAN, mean_gt_density + 0.15)

    if median_area > dynamic_max_median:
        raise optuna.exceptions.TrialPruned(f"Trivial Permissive: {median_area:.2f} > {dynamic_max_median:.2f}")

    return mean_pos_recall

